@pytest.mark.asyncio
async def test_copy_prefix_local_folder(tmp_path):
    client = MinIOClient.__new__(MinIOClient)
    client._backend = "folder"
    client._bucket = "monitor"
    client._local_root = tmp_path
    client._fallback_to_local = False

    (tmp_path / "monitor" / "abc123" / "img1.png").parent.mkdir(parents=True)
    (tmp_path / "monitor" / "abc123" / "img1.png").write_bytes(b"one")
    (tmp_path / "monitor" / "abc123" / "sub" / "img2.png").parent.mkdir(parents=True)
    (tmp_path / "monitor" / "abc123" / "sub" / "img2.png").write_bytes(b"two")
    (tmp_path / "monitor" / "other" / "x.png").parent.mkdir(parents=True)
    (tmp_path / "monitor" / "other" / "x.png").write_bytes(b"skip")

    result = await client.copy_prefix("abc123/", "def456/")
    assert result == {"src_prefix": "abc123/", "dst_prefix": "def456/", "copied": 2}
    assert (tmp_path / "monitor" / "def456" / "img1.png").read_bytes() == b"one"
    assert (tmp_path / "monitor" / "def456" / "sub" / "img2.png").read_bytes() == b"two"
    assert not (tmp_path / "monitor" / "def456" / "other").exists()


