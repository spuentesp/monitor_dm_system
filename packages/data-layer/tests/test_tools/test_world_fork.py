@pytest.mark.unit
def test_clone_collection_scrolls_and_upserts(monkeypatch):
    point = MagicMock(id=1, vector=[0.1, 0.2], payload={"universe_id": "src"})
    fake_client = MagicMock()
    fake_client.get_collection = AsyncMock(
        return_value=MagicMock(
            config=MagicMock(params=MagicMock(vectors={"dense": MagicMock(size=2, distance="Cosine")}))
        )
    )
    fake_client.collection_exists = AsyncMock(return_value=False)
    fake_client.create_collection = AsyncMock()
    fake_client.delete_collection = AsyncMock()
    # two pages then end (offset None)
    fake_client.scroll = AsyncMock(side_effect=[([point], "off1"), ([point], None)])
    fake_client.upsert = AsyncMock()

    qdrant = MagicMock()
    qdrant.get_client.return_value = fake_client
    qdrant._ensure_payload_indexes = AsyncMock()

    monkeypatch.setattr(qdrant_tools, "get_qdrant_client", lambda: qdrant)
    monkeypatch.setattr(qdrant_tools, "run_sync", _run)

    result = qdrant_tools.qdrant_clone_collection("src_coll", "dst_coll", batch_size=5000)

    assert result == {"src_collection": "src_coll", "dst_collection": "dst_coll", "points_copied": 2}
    fake_client.create_collection.assert_awaited_once()
    assert fake_client.upsert.await_count == 2
    # batch clamped to 1024
    assert fake_client.scroll.await_args_list[0].kwargs["limit"] == 1024


